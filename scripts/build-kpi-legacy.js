#!/usr/bin/env node
// Freezes pre-Omega history (Beta + Alpha, every settled day before OMEGA_START) into
// netlify/functions/lib/kpi-legacy-alpha.json so /api/get-results-omega can show one
// all-versions cumulative without regrading ~190 days of ESPN scores on every load.
//
// Usage: node scripts/build-kpi-legacy.js <get-results-alpha.json | https://webetsocial.com/api/get-results-alpha?refresh=1>
// Source of truth for these rows is get-results-alpha (same grader the /alpha page uses).
// Refuses to write if any legacy day still has a pending pick.
const fs = require('fs');
const path = require('path');

const OMEGA_START = '2026-09-22';
const OUT = path.join(__dirname, '..', 'netlify/functions/lib/kpi-legacy-alpha.json');

async function load(src) {
  if (/^https?:/.test(src)) { const r = await fetch(src); if (!r.ok) throw new Error('HTTP ' + r.status); return r.json(); }
  let t = fs.readFileSync(src, 'utf8');
  t = t.slice(t.indexOf('{'));
  return JSON.parse(t);
}

(async () => {
  const src = process.argv[2];
  if (!src) { console.error('usage: build-kpi-legacy.js <file|url>'); process.exit(1); }
  const data = await load(src);
  const days = (data.days || []).filter(d => d.date < OMEGA_START).sort((a, b) => a.date < b.date ? 1 : -1);
  const pending = days.filter(d => d.pending > 0 || d.parlayResult === 'pending');
  if (pending.length) { console.error('Refusing: pending legacy days', pending.map(d => d.date)); process.exit(1); }
  const slim = days.map(d => ({
    date: d.date, dateFormatted: d.dateFormatted, source: d.source, noPlays: !!d.noPlays,
    wins: d.wins, losses: d.losses, pushes: d.pushes, pending: 0,
    accuracy: d.accuracy, wagered: d.wagered, profit: d.profit, roi: d.roi,
    parlayResult: d.parlayResult, parlayProfit: d.parlayProfit || 0,
    ...(d.parlayRisk ? { parlayRisk: d.parlayRisk } : {}),
    picks: (d.picks || []).map(p => ({ sport: p.sport, matchup: p.matchup, pick: p.pick, betType: p.betType, odds: p.odds, units: p.units, result: p.result, profit: p.profit, score: p.score || null })),
  }));
  const out = {
    note: 'Frozen pre-Omega KPI history (Beta then Alpha). Generated by scripts/build-kpi-legacy.js from get-results-alpha. Do not hand-edit.',
    from: slim.length ? slim[slim.length - 1].date : null,
    through: slim.length ? slim[0].date : null,
    omegaStart: OMEGA_START,
    generatedAt: new Date().toISOString(),
    days: slim,
  };
  fs.writeFileSync(OUT, JSON.stringify(out));
  console.log(`wrote ${slim.length} days ${out.from}..${out.through} to ${path.relative(process.cwd(), OUT)} (${fs.statSync(OUT).size} bytes)`);
})().catch(e => { console.error(e); process.exit(1); });
